export const PHROM_YAN_DECK_SIZE = PHROM_YAN_DECK.length;

/** จำนวนไพ่คว่ำที่วางให้เลือกในแต่ละรอบ */
export const SPREAD_SIZE = 7;

/** สุ่มไพ่คว่ำมาวางให้เลือก โดยไม่ซ้ำกันในรอบเดียว */
export function dealSpread(): PhromYanCard[] {
  const deck = [...PHROM_YAN_DECK];

  for (let i = deck.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }

  return deck.slice(0, SPREAD_SIZE);
}
