function scoreFrom(rng: Rng): number {
  // ถ่วงน้ำหนักให้ออก 3–4 ดาวบ่อยกว่า 1 หรือ 5 เพื่อไม่ให้ดูสุดโต่งเกินไป
  const roll = rng();
  if (roll < 0.08) return 1;
  if (roll < 0.28) return 2;
  if (roll < 0.62) return 3;
  if (roll < 0.9) return 4;
  return 5;
}

/**
 * สร้างคำทำนาย
 * @param periodKey คีย์ของช่วงเวลา เช่น "2026-08-27" / "2026-08-24" / "2026-08"
 *                  ต้องส่งมาจาก server เพื่อให้ client คำนวณได้ผลตรงกัน
 */
export function getFortune(
  zodiac: Zodiac,
  period: PeriodType,
  periodKey: string,
): Fortune {
  const rng = createRng(`${zodiac.id}:${period}:${periodKey}`);

  const overview = pick(rng, OVERVIEW);
  const sections: FortuneSection[] = [
    { key: "love", title: "ความรัก", emoji: "💗", score: scoreFrom(rng), text: pick(rng, LOVE) },
    { key: "work", title: "การงาน", emoji: "💼", score: scoreFrom(rng), text: pick(rng, WORK) },
    { key: "money", title: "การเงิน", emoji: "💰", score: scoreFrom(rng), text: pick(rng, MONEY) },
    { key: "health", title: "สุขภาพ", emoji: "🌿", score: scoreFrom(rng), text: pick(rng, HEALTH) },
  ];

  const overallScore = Math.round(
    sections.reduce((sum, section) => sum + section.score, 0) / sections.length,
  );

  const first = pickInt(rng, 0, 9);
  let second = pickInt(rng, 0, 9);
  if (second === first) second = (second + 3) % 10;

  return {
    zodiac,
    period,
    overallScore,
    overview,
    sections,
    luckyNumbers: [first, second],
    luckyColor: pick(rng, LUCKY_COLOR_NAMES),
    advice: pick(rng, ADVICE),
  };
}
