/**
 * เลขชีวิต = บวกเลขวันเดือนปีเกิดทุกหลักแล้วลดเหลือหลักเดียว
 * เช่น 12/8/1997 → 1+2+8+1+9+9+7 = 37 → 3+7 = 10 → 1+0 = 1
 */
export function getLifeNumber(birth: BirthDate): LifeNumber {
  const digits = `${birth.day}${birth.month}${birth.year}`;

  let sum = digits
    .split("")
    .reduce((total, digit) => total + Number(digit), 0);

  while (sum > 9) {
    sum = String(sum)
      .split("")
      .reduce((total, digit) => total + Number(digit), 0);
  }

  return LIFE_NUMBERS[sum - 1] ?? LIFE_NUMBERS[0];
}
