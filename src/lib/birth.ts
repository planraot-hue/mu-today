import { THAI_DAY_NAMES, THAI_MONTH_NAMES } from "@/lib/thai-date";

/**
 * ดวงตามวันเดือนปีเกิด อิงคติโหราศาสตร์ไทย
 *
 * วันเกิดคำนวณจากวันที่แบบ UTC ล้วน เพื่อไม่ให้ timezone ของเครื่องผู้ใช้
 * ทำให้วันเกิดเพี้ยนไปหนึ่งวัน
 */

export type BirthDate = {
  /** 1–31 */
  day: number;
  /** 1–12 */
  month: number;
  /** ค.ศ. */
  year: number;
};

/** หาว่าวันนั้นเป็นวันอะไรในสัปดาห์ (0 = อาทิตย์) */
export function getWeekdayOf(birth: BirthDate): number {
  return new Date(Date.UTC(birth.year, birth.month - 1, birth.day)).getUTCDay();
}

/** ตรวจว่าวันที่ที่กรอกมามีอยู่จริงไหม เช่น 31 กุมภาพันธ์ ไม่ผ่าน */
export function isValidBirthDate(birth: BirthDate): boolean {
  const date = new Date(Date.UTC(birth.year, birth.month - 1, birth.day));
  return (
    date.getUTCFullYear() === birth.year &&
    date.getUTCMonth() === birth.month - 1 &&
    date.getUTCDate() === birth.day
  );
}

/** "12 สิงหาคม 2540" */
export function formatBirthDate(birth: BirthDate): string {
  return `${birth.day} ${THAI_MONTH_NAMES[birth.month - 1]} ${birth.year + 543}`;
}

/** จำนวนวันในเดือนนั้น ใช้จำกัดตัวเลือกวันในฟอร์ม */
export function daysInMonth(month: number, year: number): number {
  return new Date(Date.UTC(year, month, 0)).getUTCDate();
}

