export type ChineseYearFortune = {
  overview: string;
  money: string;
  work: string;
  love: string;
  health: string;
  luckyNumbers: number[];
  luckyColor: string;
};

const LUCKY_COLORS = [
  "แดงมงคล",
  "ทองอร่าม",
  "เขียวหยก",
  "ฟ้าใส",
  "ชมพูอ่อน",
  "ขาวมุก",
  "ม่วงลาเวนเดอร์",
];

/** ดวงประจำปีของนักษัตร คงที่ตลอดปีเพราะ seed มาจาก (นักษัตร + ปี) */
export function getYearFortune(
  animal: ChineseAnimal,
  year: number,
): ChineseYearFortune {
  const rng = createRng(`chinese:${animal.name}:${year}`);

  const first = Math.floor(rng() * 9) + 1;
  let second = Math.floor(rng() * 9) + 1;
  if (second === first) second = (second % 9) + 1;

  return {
    overview: pick(rng, YEAR_OVERVIEW),
    money: pick(rng, YEAR_MONEY),
    work: pick(rng, YEAR_WORK),
    love: pick(rng, YEAR_LOVE),
    health: pick(rng, YEAR_HEALTH),
    luckyNumbers: [first, second],
    luckyColor: pick(rng, LUCKY_COLORS),
  };
}
