export type ChineseProfile = {
  animal: ChineseAnimal;
  element: ChineseElement;
  /** หยินหรือหยาง ตามปีคู่ปีคี่ */
  polarity: "หยาง" | "หยิน";
  /** true ถ้าเกิดต้นปีจนอาจคาบเกี่ยวกับตรุษจีน */
  nearNewYear: boolean;
  /** นักษัตรของปีก่อนหน้า สำหรับคนที่เกิดก่อนตรุษจีน */
  previousAnimal: ChineseAnimal;
};

/** หานักษัตรจากปี ค.ศ. — ปี 4 เป็นปีชวดตามรอบ 12 ปี */
export function getAnimalOfYear(year: number): ChineseAnimal {
  return CHINESE_ANIMALS[(((year - 4) % 12) + 12) % 12];
}

export function getElementOfYear(year: number): ChineseElement {
  // ธาตุเปลี่ยนทุก 2 ปี ครบรอบ 10 ปี
  const index = Math.floor(((((year - 4) % 10) + 10) % 10) / 2);
  return CHINESE_ELEMENTS[index];
}

export function getChineseProfile(
  year: number,
  month: number,
  day: number,
): ChineseProfile {
  return {
    animal: getAnimalOfYear(year),
    element: getElementOfYear(year),
    polarity: year % 2 === 0 ? "หยาง" : "หยิน",
    // ตรุษจีนตกช่วง 21 ม.ค. – 20 ก.พ. ใครเกิดในช่วงนี้ต้องเช็กวันตรุษจีนของปีนั้นเอง
    nearNewYear: month === 1 || (month === 2 && day <= 20),
    previousAnimal: getAnimalOfYear(year - 1),
  };
}

/** นักษัตรที่ชงกัน = ห่างกัน 6 ตำแหน่งในวงล้อ */
export function getClashAnimal(animal: ChineseAnimal): ChineseAnimal {
  return CHINESE_ANIMALS[(animal.index + 6) % 12];
}

export type ClashLevel = "ชงตรง" | "คัดชง" | "ปกติ";

/** ตรวจว่าปีนี้ชงกับนักษัตรของเราหรือไม่ */
export function getClashWithYear(
  animal: ChineseAnimal,
  currentYear: number,
): { level: ClashLevel; yearAnimal: ChineseAnimal; note: string } {
  const yearAnimal = getAnimalOfYear(currentYear);
  const distance = (((animal.index - yearAnimal.index) % 12) + 12) % 12;

  if (distance === 6) {
    return {
      level: "ชงตรง",
      yearAnimal,
      note: "ปีนี้เป็นปีชงตรงของคุณ คนโบราณแนะนำให้ทำบุญสะเดาะเคราะห์ และระวังการตัดสินใจเรื่องใหญ่",
    };
  }
  if (distance === 3 || distance === 9) {
    return {
      level: "คัดชง",
      yearAnimal,
      note: "ปีนี้คัดชงเล็กน้อย ไม่ถึงกับหนัก แต่ให้ระวังเรื่องสุขภาพและการเดินทาง",
    };
  }
  return {
    level: "ปกติ",
    yearAnimal,
    note: "ปีนี้ไม่ชงกับนักษัตรของคุณ ถือว่าเป็นปีที่ราบรื่นตามปกติ",
  };
}

