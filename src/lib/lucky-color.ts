export type DailyCharm = {
  charm: string;
  direction: string;
  luckyNumber: number;
};

export function getDailyCharm(isoDate: string): DailyCharm {
  const rng = createRng(`charm:${isoDate}`);
  return {
    charm: pick(rng, LUCKY_CHARMS),
    direction: pick(rng, LUCKY_DIRECTIONS),
    luckyNumber: Math.floor(rng() * 9) + 1,
  };
}
